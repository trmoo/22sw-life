/* © 2026 티쳐무 · 모든 권리 보유 — 「소프트웨어와 생활」 웹 교과서
   ─────────────────────────────────────────────────────────────
   교육과정 데이터 검사 — content/curriculum.json

   좌측 단원 나무, 성취기준 색인, 교과서 대조표가 모두 이 파일에서 나온다.
   여기가 어긋나면 화면 전체가 조용히 틀린다. 그래서 빌드 맨 앞에서 본다.

     1. 성취기준 코드가 고시 형식([12소생NN-NN])이고, 단원 번호와 맞는가
     2. 성취기준이 19개 모두 있는가 (고시문 기준 영역별 3·4·4·4·4)
     3. 차시 번호가 1부터 빈칸 없이 이어지는가
     4. 차시가 담당하는 성취기준이 그 단원에 실제로 있는가
     5. 모든 성취기준을 담당하는 차시가 하나 이상 있는가 (커버리지)
     6. 출판사 매핑이 등록된 출판사 코드만 쓰는가
     7. 메타의 총차시가 실제 차시 수와 같은가
   ───────────────────────────────────────────────────────────── */
import { readFileSync } from 'node:fs';

const 경로 = process.argv[2] ?? 'content/curriculum.json';
const data = JSON.parse(readFileSync(경로, 'utf8'));
const 오류 = [];

const 기대개수 = { 1: 3, 2: 4, 3: 4, 4: 4, 5: 4 };
const 출판사코드 = new Set(data.출판사.map((p) => p.코드));
const 상태들 = new Set(['draft', 'review', 'published']);
let 차시합 = 0;

for (const u of data.단원) {
  const n = u.단원번호;
  const 코드들 = new Set();
  for (const s of u.성취기준) {
    if (!/^12소생\d{2}-\d{2}$/.test(s.코드)) 오류.push(`형식이 틀린 코드: ${s.코드}`);
    if (Number(s.코드.slice(4, 6)) !== n) 오류.push(`${s.코드} 가 ${n}단원에 들어 있다`);
    if (!s.본문?.trim()) 오류.push(`${s.코드} 본문이 비었다`);
    // ⚠ 성취기준 정리본의 맨 끝 색인표(코드 | 과목 | 영역 | 본문)를 함께 긁으면 본문 자리에
    //   과목 이름이 들어간다(2026-11-08 실제로 19개 모두 「소프트웨어와 생활」 이었다).
    //   성취기준 문장은 「~한다.」 로 끝나는 한 문장이다.
    else if (s.본문.trim() === '소프트웨어와 생활' || !/다\.$/.test(s.본문.trim()) || s.본문.length < 25) {
      오류.push(`${s.코드} 본문이 성취기준 문장이 아니다: 「${s.본문}」`);
    }
    코드들.add(s.코드);
    for (const k of Object.keys(s.출판사별매핑 ?? {})) {
      if (!출판사코드.has(k)) 오류.push(`${s.코드}: 등록되지 않은 출판사 코드 ${k}`);
    }
  }
  if (u.성취기준.length !== 기대개수[n]) {
    오류.push(`${n}단원 성취기준이 ${u.성취기준.length}개다 (고시문은 ${기대개수[n]}개)`);
  }
  const 담당됨 = new Set();
  u.차시.forEach((l, i) => {
    if (l.차시번호 !== i + 1) 오류.push(`${n}단원: ${i + 1}번째 차시의 번호가 ${l.차시번호}다`);
    if (!l.차시명?.trim()) 오류.push(`${n}-${l.차시번호}: 차시명이 비었다`);
    if (!l.학습목표?.length) 오류.push(`${n}-${l.차시번호}: 학습목표가 없다`);
    if (!상태들.has(l.상태)) 오류.push(`${n}-${l.차시번호}: 상태 값이 이상하다 (${l.상태})`);
    for (const c of l.담당성취기준) {
      if (!코드들.has(c)) 오류.push(`${n}-${l.차시번호}: 이 단원에 없는 성취기준 ${c}`);
      담당됨.add(c);
    }
  });
  for (const c of 코드들) if (!담당됨.has(c)) 오류.push(`${c} 를 담당하는 차시가 없다`);
  차시합 += u.차시.length;
}

const 전체 = data.단원.reduce((a, u) => a + u.성취기준.length, 0);
if (전체 !== 19) 오류.push(`성취기준이 모두 ${전체}개다 (19개여야 한다)`);
if (data.메타.총차시 !== 차시합) 오류.push(`메타 총차시 ${data.메타.총차시} ≠ 실제 ${차시합}`);

if (오류.length) {
  console.error(`\n✗ 교육과정 데이터 검사 실패 — ${오류.length}건`);
  for (const e of 오류) console.error('  · ' + e);
  process.exit(1);
}
console.log(`✓ 교육과정 데이터 — 단원 ${data.단원.length} · 성취기준 ${전체} · 차시 ${차시합} · 커버리지 100%`);
