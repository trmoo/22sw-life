def 계절(m):
    return {12: "겨울", 1: "겨울", 2: "겨울", 3: "봄", 4: "봄", 5: "봄",
            6: "여름", 7: "여름", 8: "여름"}.get(m, "가을")


# ---------------------------------------------------------------- bike.csv
행 = []
d = date(2025, 1, 1)
장마 = set(range(173, 205))  # 6월 하순~7월 하순, 비 오는 날이 잦다
while d.year == 2025:
    n = d.timetuple().tm_yday
    # 기온: 1월 중순이 가장 춥고 8월 초가 가장 덥다
    기온 = 13.0 - 15.0 * math.cos(2 * math.pi * (n - 18) / 365) + rnd.gauss(0, 2.6)
    비올확률 = 0.55 if n in 장마 else 0.18
    강수 = 0.0
    if rnd.random() < 비올확률:
        강수 = round(min(120.0, rnd.expovariate(1 / (22 if n in 장마 else 9))), 1)
    # 미세먼지: 늦겨울~봄에 높고 비 오는 날 낮다
    먼지 = 38 + 22 * math.cos(2 * math.pi * (n - 70) / 365) + rnd.gauss(0, 11)
    if 강수 > 0:
        먼지 *= 0.6
    먼지 = max(5, round(먼지))

    w = d.weekday()
    주말 = w >= 5
    기본 = 2600 if 주말 else 2300
    # 기온 효과: 21℃ 안팎이 가장 좋고 너무 추워도 너무 더워도 준다
    온도효과 = math.exp(-((기온 - 21) ** 2) / (2 * 9.5 ** 2))
    비효과 = 1.0 if 강수 == 0 else max(0.18, 1 - 강수 / 35)
    먼지효과 = 1.0 if 먼지 < 50 else max(0.6, 1 - (먼지 - 50) / 120)
    주말효과 = (1.0 + 0.35 * 온도효과) if 주말 else 1.0  # 날씨 좋은 주말은 나들이로 는다
    대여 = 기본 * (0.25 + 0.95 * 온도효과) * 비효과 * 먼지효과 * 주말효과
    대여 = max(80, round(대여 * rnd.uniform(0.9, 1.1)))

    행.append({
        "날짜": d.isoformat(), "월": d.month, "요일": 요일이름[w], "계절": 계절(d.month),
        "평균기온": round(기온, 1), "강수량": 강수, "미세먼지": 먼지, "대여건수": 대여,
    })
    d += timedelta(days=1)

bike = pd.DataFrame(행)
bike.to_csv(OUT / "bike.csv", index=False, encoding="utf-8")

