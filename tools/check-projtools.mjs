참('새 화면 id 는 겹치지 않는다', P.새화면id(P.시안예시) === 's5' && !P.시안예시.화면.some((h) => h.id === P.새화면id(P.시안예시)));
참('흐름 지도: 예시는 길 7개 (단추마다 하나)', P.시안흐름(P.시안예시).length === 7);
