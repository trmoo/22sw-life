참('내려받는 시안: 화면 넷이 다 들어 있다', ['s1', 's2', 's3', 's4'].every((id) => 파일.includes(`id="${id}"`)));
참('내려받는 시안: 첫 화면만 보인다', (파일.match(/<section class="sc" id="s\d"(?! hidden)/g) ?? []).length === 1);
참('내려받는 시안: 제목을 이스케이프한다', 파일.includes('찾아줘 &lt;우리&gt; 학교') && !파일.includes('<우리>'));
참('내려받는 시안: 저작권 표시', 파일.includes('© 2026 티쳐무'));
참('내려받는 시안: 바깥으로 보내는 코드가 없다', !/fetch\(|XMLHttpRequest|sendBeacon|https?:\/\//.test(파일));
참('요소HTML: 글을 이스케이프한다', P.요소HTML({ 종류: '글', 글: '<b>x</b>' }) === '<p class="pv-p">&lt;b&gt;x&lt;/b&gt;</p>');

/* ---------- 작업 보드 ---------- */
