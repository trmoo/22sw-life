참('페르소나 → 캔버스: 적은 고객군을 덮지 않는다', P.페르소나에서캔버스(서윤, { customer: '내 고객' }).customer === '내 고객');

/* ---------- 시안 ---------- */
참('예시 시안은 점검 문제 0개', P.시안점검(P.시안예시).length === 0);
참('새 시안(화면 하나)은 문제 0개', P.시안점검(P.새시안()).length === 0);
const 고장 = JSON.parse(JSON.stringify(P.시안예시));
