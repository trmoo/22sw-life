참('삼각형 꼭짓점: 위 · 오른쪽 아래 · 왼쪽 아래', 꼭[0][0] === 150 && 꼭[0][1] === 40 && 꼭[1][0] > 150 && 꼭[2][0] < 150 && 꼭[1][1] === 꼭[2][1]);
참('평균 0 이면 중심', P.삼각좌표({}).every((p) => p[0] === 150 && p[1] === 140));

/* ---------- MDX 의 store= · from= ---------- */
const 도구 = new Map(); // id → 컴포넌트 이름
const 참조 = [];
const 폴더 = 'content/units';
for (const u of readdirSync(폴더)) {
  const d = join(폴더, u);
  for (const f of readdirSync(d).filter((x) => x.endsWith('.mdx'))) {
    const 글 = readFileSync(join(d, f), 'utf8');
    for (const m of 글.matchAll(/<(PersonaMaker|LeanCanvas|ProtoBuilder|TaskBoard|ValueReview)\b([^>]*)>/g)) {
      const id = m[2].match(/\bid="([^"]+)"/)?.[1];
      도구.set(id, m[1]);
      const store = m[2].match(/\bstore="([^"]+)"/)?.[1];
      const from = m[2].match(/\bfrom="([^"]+)"/)?.[1];
      if (store) 참조.push({ 곳: `${u}/${f}`, 종류: m[1], 가리킴: store, 바라는: m[1] });
      if (from) 참조.push({ 곳: `${u}/${f}`, 종류: m[1], 가리킴: from, 바라는: 'PersonaMaker' });
    }
  }
}
for (const r of 참조) {
  참(`${r.곳}: ${r.종류} 가 가리키는 ${r.가리킴} 은 ${r.바라는} 이어야 한다`, 도구.get(r.가리킴) === r.바라는);
}
참('Ⅴ단원 MDX 가 있다', existsSync('content/units/05'));

if (오류.length) {
  console.error(`✗ 프로젝트 도구 점검 실패 ${오류.length}건 (통과 ${통과})`);
  for (const e of 오류) console.error('  - ' + e);
  process.exit(1);
}
console.log(`✓ 프로젝트 도구 점검 ${통과}가지 통과 (페르소나·린 캔버스·시안·작업 보드·가치 평가, store/from ${참조.length}곳)`);
