참('문제·해결 줄 수가 다르면 실패', 결과(P.캔버스점검({ ...P.캔버스예시, solution: '하나\n둘' }), 'pair') === false);
참('긴 가치 제안을 잡는다', 결과(P.캔버스점검({ ...P.캔버스예시, uvp: '가'.repeat(51) }), 'uvp') === false);
참('두 줄 가치 제안을 잡는다', 결과(P.캔버스점검({ ...P.캔버스예시, uvp: '첫 줄\n둘째 줄' }), 'uvp') === false);
참('셀 수 없는 지표를 잡는다', 결과(P.캔버스점검({ ...P.캔버스예시, metric: '만족도가 높아진다' }), 'metric') === false);
