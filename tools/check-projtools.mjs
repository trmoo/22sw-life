참('진행률', P.보드진행(보드).다함 === 1 && P.보드진행(보드).비율 === 0.25 && P.보드진행({}).비율 === 0);
참('새 보드는 팀원 칸 셋, 카드 없음', P.새보드().사람.length === 3 && P.새보드().카드.length === 0);

/* ---------- 가치 평가 ---------- */
참('관점 셋 × 기준 넷', P.관점들.length === 3 && P.관점들.every((관) => 관.기준.length === 4));
const 우리 = { social: [4, 4, 3, 3], function: [3, 2, 2, 3], ethic: [4, 3, 4, 4] };
const 동료 = { social: [4, 2, 3, 3], function: [1, 2, 2, 3], ethic: [0, 0, 0, 0] };
const 요 = P.가치요약(우리, 동료);
참('평균: 사회 3.5 · 기능 2.5 · 윤리 3.75', 요.우리.social === 3.5 && 요.우리.function === 2.5 && 요.우리.ethic === 3.75);
