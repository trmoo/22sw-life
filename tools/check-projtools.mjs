  사람: [{ 별명: '해', 역할: ['기획', '기록·발표'] }, { 별명: '달', 역할: ['화면 설계', '시험'] }, { 별명: '별', 역할: ['개발'] }],
  카드: [{ 글: 'a', 담당: '해', 칸: 0 }, { 글: 'b', 담당: '달', 칸: 1 }, { 글: 'c', 담당: '별', 칸: 2 }, { 글: 'd', 담당: '별', 칸: 1 }],
