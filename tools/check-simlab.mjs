/**
 * Ⅳ단원 시뮬레이션 엔진 점검
 *
 *   node tools/check-simlab.mjs
 *
 * 무작위 시뮬레이션은 «답이 하나»가 아니라서 값 하나를 맞추는 대신 **성질**을 본다.
 *   - 같은 씨앗이면 같은 결과 (재현성)
 *   - 사람 수·자전거 수가 저절로 생기거나 사라지지 않는다 (보존)
 *   - 변수를 바꾸면 본문이 말하는 방향으로 결과가 움직인다 (본문 주장과 엔진이 어긋나지 않게)
 * 그리고 SIR 방정식은 본문 파이썬 예제와 같은 식이므로 **파이썬으로 계산한 값과 대조**한다.
 */
import { spawnSync } from 'node:child_process';
import * as S from '../src/lib/simlab.js';

const 오류 = [];
let 통과 = 0;
const 참 = (이름, 조건) => (조건 ? 통과++ : 오류.push(이름));

/* ---------- 난수 ---------- */
const a = S.난수(42), b = S.난수(42), c = S.난수(43);
const 줄a = Array.from({ length: 5 }, a), 줄b = Array.from({ length: 5 }, b), 줄c = Array.from({ length: 5 }, c);
참('같은 씨앗 → 같은 난수', JSON.stringify(줄a) === JSON.stringify(줄b));
참('다른 씨앗 → 다른 난수', JSON.stringify(줄a) !== JSON.stringify(줄c));
const r = S.난수(1);
let 합 = 0, 범위안 = true;
for (let i = 0; i < 100000; i++) { const x = r(); 합 += x; if (x < 0 || x >= 1) 범위안 = false; }
참('난수는 0 이상 1 미만', 범위안);
참('난수 평균 ≈ 0.5', Math.abs(합 / 100000 - 0.5) < 0.01);

/* ---------- 대여소 ---------- */
const 하루 = S.대여소하루({ 처음: 10 }, S.난수(3));
참('대여소: 시각 기록 17칸(6~22시)', 하루.기록.length === 17);
참('대여소: 자전거 수 보존 (처음 − 빌림 + 반납 = 마지막)', 10 - 하루.빌림 + 하루.반납 === 하루.기록.at(-1).자전거);
참('대여소: 자전거 수는 0 ~ 30', 하루.기록.every((x) => x.자전거 >= 0 && x.자전거 <= 30));
참('대여소: 같은 씨앗 같은 하루', JSON.stringify(S.대여소하루({ 처음: 10 }, S.난수(3))) === JSON.stringify(하루));
const 비율 = (변수) => S.대여소여러날(변수, 1000, S.난수(7)).비율;
const 처음5 = 비율({ 처음: 5 }), 처음15 = 비율({ 처음: 15 }), 처음25 = 비율({ 처음: 25 });
참(`대여소: 처음 자전거가 많을수록 헛걸음 날이 준다 (${처음5}, ${처음15}, ${처음25})`, 처음5 >= 처음15 && 처음15 > 처음25);
참('대여소: 트럭이 오면 헛걸음 날이 준다', 비율({ 처음: 15, 트럭: 10 }) < 비율({ 처음: 15 }));
참('대여소: 이용자가 많아지면 헛걸음 날이 는다', 비율({ 처음: 20, 세기: 1.3 }) > 비율({ 처음: 20, 세기: 0.7 }));
/* 본문 4차시 — «많이 가져다 놓으면 저녁에 거치대가 넘친다» */
const 넘침 = (변수) => { let n = 0; for (let i = 0; i < 500; i++) if (S.대여소하루(변수, S.난수(100 + i)).반납실패 > 0) n++; return n / 500; };
참('대여소: 처음 자전거가 많으면 저녁에 반납 못 하는 날이 는다', 넘침({ 처음: 25, 트럭: 5 }) > 넘침({ 처음: 10 }));

/* ---------- 급식 줄 ---------- */
const 줄 = (변수) => S.급식줄({ 학생: 120, 배식초: 20, ...변수 }, S.난수(5));
const 하나 = 줄({ 배식대: 1 }), 둘 = 줄({ 배식대: 2 }), 나눠 = 줄({ 배식대: 1, 나눠서: true });
참('급식: 배식대가 둘이면 평균 대기가 준다', 둘.평균대기 < 하나.평균대기);
참('급식: 학년별로 나눠 오면 평균 대기가 준다', 나눠.평균대기 < 하나.평균대기);
참('급식: 배식대가 둘이면 일찍 끝난다', 둘.끝 < 하나.끝);
참('급식: 줄 길이는 음수가 아니다', 하나.기록.every((x) => x.줄 >= 0));
참('급식: 최대 대기 ≥ 평균 대기', 하나.최대대기 >= 하나.평균대기);

/* ---------- 원주율 ---------- */
const 작은 = S.원주율(100, S.난수(11)), 큰 = S.원주율(1000000, S.난수(11));
참('원주율: 백만 번이면 0.01 안쪽', Math.abs(큰.어림 - Math.PI) < 0.01);
참('원주율: 점 보관 개수 지킴', S.원주율(500, S.난수(1), 50).점들.length === 50);
const 이어 = S.원주율(300, S.난수(2), 0, S.원주율(200, S.난수(9)));
참('원주율: 이어서 던지면 n 이 더해진다', 이어.n === 500);
let 오차합100 = 0, 오차합1만 = 0;
for (let s = 1; s <= 40; s++) {
  오차합100 += Math.abs(S.원주율(100, S.난수(s)).어림 - Math.PI);
  오차합1만 += Math.abs(S.원주율(10000, S.난수(s)).어림 - Math.PI);
}
참('원주율: 많이 던질수록 평균 오차가 준다 (대수의 법칙)', 오차합1만 < 오차합100 / 3);
참('원주율: 100번은 흔들린다 (작은 표본)', 작은.n === 100);

/* ---------- SIR 방정식 ---------- */
const 기본 = S.sir방정식({});
참('SIR: S+I+R = N 이 날마다 유지', 기본.기록.every((x) => Math.abs(x.S + x.I + x.R - 10000) < 1e-6));
참('SIR: S 는 줄기만 한다', 기본.기록.every((x, i, arr) => i === 0 || x.S <= arr[i - 1].S + 1e-9));
const 느린 = S.sir방정식({ 베타: 0.15 });
참('SIR: 베타를 낮추면 정점이 낮고 늦다 (곡선 평탄화)', 느린.정점감염 < 기본.정점감염 && 느린.정점날 > 기본.정점날);
참('SIR: 백신 비율이 높으면 정점이 낮다', S.sir방정식({ 백신: 0.5 }).정점감염 < 기본.정점감염);
참('SIR: 베타 < 감마 면 퍼지지 않는다 (R0 < 1)', S.sir방정식({ 베타: 0.08, 감마: 0.1 }).정점감염 <= 10 + 1e-9);

/* 파이썬 예제(7차시)와 같은 식 — 파이썬으로 계산해 대조한다 */
const PY = ['python', 'python3', 'py'].find((x) => !spawnSync(x, ['--version']).error);
if (PY) {
  const 코드 = [
    'N, I, R = 10000, 10, 0',
    'S = N - I - R',
    'beta, gamma = 0.3, 0.1',
    'peak_day, peak_I = 0, I',
    'for day in range(1, 161):',
    '    new_inf = beta * S * I / N',
    '    new_rec = gamma * I',
    '    S, I, R = S - new_inf, I + new_inf - new_rec, R + new_rec',
    '    if I > peak_I:',
    '        peak_day, peak_I = day, I',
    'print(peak_day, repr(peak_I), repr(S))',
  ].join('\n');
  const p = spawnSync(PY, ['-c', 코드], { encoding: 'utf8' });
  const [날, 정점, 남은S] = p.stdout.trim().split(/\s+/).map(Number);
  참(`SIR: 정점 날이 파이썬과 같다 (${날} / ${기본.정점날})`, 날 === 기본.정점날);
  참('SIR: 정점 감염 수가 파이썬과 같다', Math.abs(정점 - 기본.정점감염) < 1e-6);
  참('SIR: 160일 뒤 S 가 파이썬과 같다', Math.abs(남은S - 기본.끝감염안됨) < 1e-6);
} else {
  console.log('  경고 파이썬이 없어 SIR 방정식 대조를 건너뛴다');
}

/* ---------- 확산(점) 모델 ---------- */
const 확산 = S.확산끝까지({}, S.난수(4));
참('확산: 사람 수 보존 (S+I+R = 200)', 확산.모델.기록.every((x) => x.S + x.I + x.R === 200));
참('확산: 끝나면 감염자 0', 확산.끝.I === 0);
참('확산: 같은 씨앗 같은 결과', S.확산끝까지({}, S.난수(4)).걸린사람 === 확산.걸린사람);
const 평균 = (변수, 키) => { let t = 0; for (let s = 1; s <= 8; s++) t += S.확산끝까지(변수, S.난수(s))[키]; return t / 8; };
const 기본걸림 = 평균({}, '걸린사람'), 거리걸림 = 평균({ 멈춤: 0.6 }, '걸린사람'), 백신걸림 = 평균({ 백신: 0.5 }, '걸린사람');
참(`확산: 거리 두기(60% 멈춤)면 걸린 사람이 준다 (${기본걸림} → ${거리걸림})`, 거리걸림 < 기본걸림 * 0.85);
참(`확산: 백신 50% 면 걸린 사람이 크게 준다 (${백신걸림})`, 백신걸림 < 기본걸림 * 0.5);
참('확산: 거리 두기면 정점이 낮아진다', 평균({ 멈춤: 0.6 }, '정점감염') < 평균({}, '정점감염') * 0.7);
const 백신모델 = S.확산만들기({ 백신: 0.5 }, S.난수(1));
참('확산: 백신 맞은 사람은 걸린 사람으로 세지 않는다', S.확산끝까지({ 백신: 0.5, 감염확률: 0 }, S.난수(1)).걸린사람 === 3 && 백신모델.면역 > 60);

if (오류.length) {
  console.error(`✗ 시뮬레이션 엔진 점검 실패 — ${오류.length}건`);
  for (const e of 오류) console.error('  · ' + e);
  process.exit(1);
}
console.log(`✓ 시뮬레이션 엔진 — ${통과}가지 (재현성·보존·변수의 방향·파이썬 대조)`);
