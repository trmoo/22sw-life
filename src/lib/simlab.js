/**
 * Ⅳ단원 시뮬레이션 엔진 (DOM 없음)
 *
 * 화면의 시뮬레이터 넷(대여소 · 급식 줄 · 원주율 · 감염병 확산)이 함께 쓴다.
 * 모든 시뮬레이션은 같은 뼈대로 짰다 — 본문 1차시에서 가르치는 «시뮬레이션의 구성 요소»가 그대로 코드에 있다.
 *
 *   변수(입력)  : 학생이 슬라이더로 바꾸는 값 — 처음 자전거 수, 배식대 수, 감염 확률 …
 *   상태        : 시간이 흐르며 바뀌는 값 — 지금 자전거 수, 줄 선 사람, S·I·R 의 수
 *   규칙        : 한 걸음마다 상태를 바꾸는 방법 — 「1분마다 이 확률로 한 대 빌려 간다」
 *   시간(반복)  : 규칙을 한 걸음씩 되풀이한다
 *   출력        : 그래프와 요약 숫자 — 헛걸음 수, 평균 대기 시간, 감염 정점
 *
 * 무작위는 씨앗을 줄 수 있는 난수(mulberry32)를 쓴다. 같은 씨앗이면 같은 결과가 나와
 * tools/check-simlab.mjs 가 성질을 시험할 수 있다. 화면에서는 씨앗을 바꿔 «매번 다른 결과»를 보여 준다.
 */

/* ------------------------------------------------------------ 난수 */

/** 씨앗을 넣으면 0 이상 1 미만의 수를 차례로 내는 함수를 돌려준다 (mulberry32) */
export function 난수(씨앗 = Date.now()) {
  let a = 씨앗 >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/* ------------------------------------------------------------ ① 대여소의 하루 (1·2·4차시) */

/**
 * 역 앞 대여소의 시간대별 «한 시간에 빌리러 오는 사람 / 반납하러 오는 사람» (기본값).
 * 아침에는 역에서 빌려 회사·학교로 가고, 저녁에는 돌아와 반납한다. 새솔시 이야기를 위해 지어낸 값이다.
 */
export const 대여소기본 = {
  시작시: 6,
  끝시: 22,
  대여: { 6: 3, 7: 9, 8: 13, 9: 7, 10: 4, 11: 4, 12: 5, 13: 4, 14: 4, 15: 4, 16: 5, 17: 7, 18: 6, 19: 5, 20: 3, 21: 3 },
  반납: { 6: 1, 7: 2, 8: 3, 9: 3, 10: 4, 11: 4, 12: 4, 13: 4, 14: 4, 15: 4, 16: 5, 17: 11, 18: 14, 19: 10, 20: 4, 21: 3 },
};

/**
 * 대여소의 하루를 1분 단위로 돌린다.
 * @param 변수 { 처음, 칸수, 세기(이용자 배율), 트럭(아침 6시 30분에 가져다 놓는 대수) }
 * @returns { 기록:[{시각, 자전거}], 헛걸음, 반납실패, 빈시간(분), 빌림, 반납 }
 */
export function 대여소하루(변수, rnd) {
  const { 처음 = 10, 칸수 = 30, 세기 = 1, 트럭 = 0 } = 변수;
  const 표 = 대여소기본;
  let 자전거 = Math.min(처음, 칸수);
  let 헛걸음 = 0, 반납실패 = 0, 빈시간 = 0, 빌림 = 0, 반납 = 0;
  const 기록 = [{ 시각: 표.시작시, 자전거 }];
  for (let 시 = 표.시작시; 시 < 표.끝시; 시++) {
    for (let 분 = 0; 분 < 60; 분++) {
      /* 규칙 0 — 6시 30분에 트럭이 와서 자전거를 내려놓는다(거치대가 차면 더 못 놓는다) */
      if (시 === 6 && 분 === 30 && 트럭 > 0) 자전거 = Math.min(칸수, 자전거 + 트럭);
      /* 규칙 1 — 이번 1분 동안 빌리러 온 사람이 있나? (한 시간 평균 ÷ 60 의 확률) */
      if (rnd() < Math.min(1, ((표.대여[시] ?? 0) * 세기) / 60)) {
        if (자전거 > 0) { 자전거--; 빌림++; } else 헛걸음++;
      }
      /* 규칙 2 — 반납하러 온 사람이 있나? 거치대가 꽉 찼으면 반납하지 못한다 */
      if (rnd() < Math.min(1, ((표.반납[시] ?? 0) * 세기) / 60)) {
        if (자전거 < 칸수) { 자전거++; 반납++; } else 반납실패++;
      }
      if (자전거 === 0) 빈시간++;
    }
    기록.push({ 시각: 시 + 1, 자전거 });
  }
  return { 기록, 헛걸음, 반납실패, 빈시간, 빌림, 반납 };
}

/** 같은 변수로 여러 날을 돌려 «헛걸음이 한 번이라도 있었던 날»의 비율을 센다 */
export function 대여소여러날(변수, 날수, rnd) {
  let 나쁜날 = 0, 헛걸음합 = 0;
  for (let i = 0; i < 날수; i++) {
    const r = 대여소하루(변수, rnd);
    if (r.헛걸음 > 0) 나쁜날++;
    헛걸음합 += r.헛걸음;
  }
  return { 날수, 나쁜날, 비율: 나쁜날 / 날수, 평균헛걸음: 헛걸음합 / 날수 };
}

/* ------------------------------------------------------------ ② 급식 줄 (5차시) */

/**
 * 급식실 줄 서기. 한 걸음 = 10초.
 * @param 변수 { 학생, 배식대, 배식초(한 명에 걸리는 평균 초), 나눠서(학년별로 5분씩 나눠 오나) }
 * 학생은 «종이 친 뒤 몇 분 안에» 무작위로 도착한다 — 한꺼번에 오면 2분 안, 나눠 오면 학년마다 5분 간격.
 * @returns { 기록:[{초, 줄}], 평균대기(초), 최대대기(초), 끝(초) }
 */
export function 급식줄(변수, rnd) {
  const { 학생 = 120, 배식대 = 1, 배식초 = 20, 나눠서 = false } = 변수;
  const 걸음 = 10;
  /* 도착 시각 만들기 */
  const 도착 = [];
  for (let i = 0; i < 학생; i++) {
    const 학년 = i % 3;
    const 시작 = 나눠서 ? 학년 * 300 : 0;
    도착.push(시작 + Math.floor(rnd() * 120));
  }
  도착.sort((a, b) => a - b);
  const 배식대남은 = Array(배식대).fill(0); // 배식대마다 «지금 손님이 끝나기까지 남은 초»
  const 줄 = [];
  let 다음 = 0, 끝낸 = 0, 대기합 = 0, 최대대기 = 0, 초 = 0;
  const 기록 = [];
  while (끝낸 < 학생 && 초 < 4 * 3600) {
    while (다음 < 학생 && 도착[다음] <= 초) 줄.push(도착[다음++]);
    for (let k = 0; k < 배식대; k++) {
      if (배식대남은[k] > 0) 배식대남은[k] = Math.max(0, 배식대남은[k] - 걸음);
      if (배식대남은[k] === 0 && 줄.length) {
        const 온시각 = 줄.shift();
        const 기다림 = 초 - 온시각;
        대기합 += 기다림;
        최대대기 = Math.max(최대대기, 기다림);
        /* 배식 시간은 평균의 0.5~1.5배 사이에서 흔들린다 — 사람마다 다르다 */
        배식대남은[k] = Math.max(걸음, Math.round((배식초 * (0.5 + rnd())) / 걸음) * 걸음);
        끝낸++;
      }
    }
    기록.push({ 초, 줄: 줄.length });
    초 += 걸음;
  }
  return { 기록, 평균대기: 대기합 / 학생, 최대대기, 끝: 초 };
}

/* ------------------------------------------------------------ ③ 몬테카를로 원주율 (6차시) */

/**
 * 한 변이 1인 정사각형에 점을 n개 뿌려, 반지름 1인 사분원 안에 든 비율 × 4 로 원주율을 어림한다.
 * @returns { 안, n, 어림, 점들(앞에서 최대 보관 개수만), 흐름:[{n, 어림}] }
 */
export function 원주율(n, rnd, 보관 = 0, 이어서 = null) {
  let 안 = 이어서?.안 ?? 0;
  let 던짐 = 이어서?.n ?? 0;
  const 점들 = [];
  const 흐름 = [];
  const 기록간격 = Math.max(1, Math.floor(n / 200));
  for (let i = 0; i < n; i++) {
    const x = rnd();
    const y = rnd();
    const 들어감 = x * x + y * y <= 1;
    if (들어감) 안++;
    던짐++;
    if (점들.length < 보관) 점들.push([x, y, 들어감]);
    if ((i + 1) % 기록간격 === 0) 흐름.push({ n: 던짐, 어림: (4 * 안) / 던짐 });
  }
  return { 안, n: 던짐, 어림: 던짐 ? (4 * 안) / 던짐 : NaN, 점들, 흐름 };
}

/* ------------------------------------------------------------ ④ 감염병 확산 (7차시) */

/**
 * SIR 방정식 모델 — 하루 단위로 계산한다(오일러 방법).
 *   새 감염 = β × S × I ÷ N,  새 회복 = γ × I
 * 본문 7차시의 파이썬 예제와 **같은 식, 같은 차례**다. tools/check-simlab.mjs 가 파이썬 결과와 대조한다.
 * @param 변수 { N, 처음감염, 베타, 감마, 일수, 백신(처음부터 면역인 비율 0~1) }
 */
export function sir방정식(변수) {
  const { N = 10000, 처음감염 = 10, 베타 = 0.3, 감마 = 0.1, 일수 = 160, 백신 = 0 } = 변수;
  let R = Math.round(N * 백신);
  let I = 처음감염;
  let S = N - I - R;
  const 기록 = [{ 날: 0, S, I, R }];
  for (let 날 = 1; 날 <= 일수; 날++) {
    const 새감염 = (베타 * S * I) / N;
    const 새회복 = 감마 * I;
    S -= 새감염;
    I += 새감염 - 새회복;
    R += 새회복;
    기록.push({ 날, S, I, R });
  }
  let 정점 = 기록[0];
  for (const r of 기록) if (r.I > 정점.I) 정점 = r;
  return { 기록, 정점날: 정점.날, 정점감염: 정점.I, 끝감염안됨: 기록[기록.length - 1].S };
}

/**
 * 행위자(점) 기반 확산 모델 — 점 하나가 사람 하나다.
 * 점들은 상자 안을 돌아다니고, 감염된 점과 가까이 스치면 확률적으로 옮는다. 정해진 날이 지나면 회복한다.
 * 화면은 한 걸음씩(애니메이션), 시험은 끝까지 한 번에 돌린다.
 */
export function 확산만들기(변수, rnd) {
  const { 사람 = 200, 처음감염 = 3, 감염확률 = 0.2, 회복걸음 = 80, 멈춤 = 0, 백신 = 0, 반경 = 0.022, 빠르기 = 0.006 } = 변수;
  const 점 = [];
  for (let i = 0; i < 사람; i++) {
    const 각 = rnd() * Math.PI * 2;
    점.push({
      x: rnd(), y: rnd(),
      dx: Math.cos(각) * 빠르기, dy: Math.sin(각) * 빠르기,
      /* 멈춤 비율만큼은 제자리에 있는다 — 거리 두기 */
      멈춤: i >= 처음감염 && rnd() < 멈춤,
      상태: i < 처음감염 ? 'I' : rnd() < 백신 ? 'R' : 'S',
      앓은: 0,
    });
  }
  const 면역 = 점.filter((p) => p.상태 === 'R').length; // 백신으로 처음부터 면역인 사람
  return { 점, 걸음: 0, 기록: [세기(점, 0)], 감염확률, 회복걸음, 반경, 면역 };
}

function 세기(점, 걸음) {
  const c = { 걸음, S: 0, I: 0, R: 0 };
  for (const p of 점) c[p.상태]++;
  return c;
}

/** 한 걸음 나아간다. 상태(모델)를 바꿔 놓고 돌려준다 */
export function 확산한걸음(모델, rnd) {
  const { 점, 감염확률, 회복걸음, 반경 } = 모델;
  for (const p of 점) {
    if (p.멈춤) continue;
    p.x += p.dx;
    p.y += p.dy;
    if (p.x < 0 || p.x > 1) { p.dx = -p.dx; p.x = Math.min(1, Math.max(0, p.x)); }
    if (p.y < 0 || p.y > 1) { p.dy = -p.dy; p.y = Math.min(1, Math.max(0, p.y)); }
  }
  /* 감염 — 감염된 점 가까이(반경 안)에 있는 S 는 이번 걸음에 감염확률로 옮는다 */
  const 아픈 = 점.filter((p) => p.상태 === 'I');
  const 새로 = [];
  for (const p of 점) {
    if (p.상태 !== 'S') continue;
    for (const q of 아픈) {
      const dx = p.x - q.x, dy = p.y - q.y;
      if (dx * dx + dy * dy < 반경 * 반경 && rnd() < 감염확률) { 새로.push(p); break; }
    }
  }
  for (const p of 새로) p.상태 = 'I';
  /* 회복 — 앓은 걸음이 회복걸음을 넘으면 R */
  for (const p of 아픈) if (++p.앓은 >= 회복걸음) p.상태 = 'R';
  모델.걸음++;
  모델.기록.push(세기(점, 모델.걸음));
  return 모델;
}

/** 감염자가 0 이 되거나 최대 걸음까지 돌린다 (시험·「한 번에 끝까지」 단추용) */
export function 확산끝까지(변수, rnd, 최대 = 2000) {
  const m = 확산만들기(변수, rnd);
  while (m.걸음 < 최대 && m.기록[m.기록.length - 1].I > 0) 확산한걸음(m, rnd);
  let 정점 = m.기록[0];
  for (const r of m.기록) if (r.I > 정점.I) 정점 = r;
  const 끝 = m.기록[m.기록.length - 1];
  /* 한 번이라도 걸린 사람 = 지금 앓는 사람 + 나은 사람 − 처음부터 면역이던 사람 */
  return { 모델: m, 정점걸음: 정점.걸음, 정점감염: 정점.I, 걸린사람: 끝.R + 끝.I - m.면역, 끝 };
}
